#!/usr/bin/env bash
# install.sh — set up the vibe-coding diary hook for Claude Code.
#
# What this does:
#   1. Copies vibe_diary_hook.py to ~/.claude/hooks/ and chmods it
#   2. Creates ~/.claude/vibe-diary.env with placeholder credentials (chmod 600)
#   3. Registers the SessionEnd hook in ~/.claude/settings.json, merging with
#      any existing hooks (no clobbering)
#   4. Runs the smoke test if Python and test_hook.py are available
#
# Idempotent: re-running won't duplicate the hook entry or overwrite credentials.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_DIR="${HOME}/.claude"
HOOKS_DIR="${CLAUDE_DIR}/hooks"
HOOK_SRC="${SCRIPT_DIR}/vibe_diary_hook.py"
HOOK_DST="${HOOKS_DIR}/vibe_diary_hook.py"
ENV_FILE="${CLAUDE_DIR}/vibe-diary.env"
SETTINGS_FILE="${CLAUDE_DIR}/settings.json"
TEST_FILE="${SCRIPT_DIR}/test_hook.py"

# ----- pretty printing -----
c_red=$'\033[31m'; c_green=$'\033[32m'; c_yellow=$'\033[33m'
c_blue=$'\033[34m'; c_bold=$'\033[1m'; c_reset=$'\033[0m'
step()  { printf "%s==>%s %s%s%s\n"    "$c_blue"  "$c_reset" "$c_bold" "$*" "$c_reset"; }
ok()    { printf "    %s✓%s %s\n"      "$c_green" "$c_reset" "$*"; }
warn()  { printf "    %s!%s %s\n"      "$c_yellow" "$c_reset" "$*"; }
err()   { printf "    %s✗%s %s\n" >&2  "$c_red"   "$c_reset" "$*"; }
info()  { printf "    %s\n" "$*"; }

fail() { err "$*"; exit 1; }

# ----- preflight -----
step "Checking prerequisites"

if ! command -v python3 >/dev/null 2>&1; then
    fail "python3 not found. The hook is a Python script; please install Python 3."
fi
ok "python3: $(command -v python3)"

# Python 3 from python.org on macOS ships without CA certificates — urllib
# then fails every HTTPS call with "CERTIFICATE_VERIFY_FAILED". The official
# fix is a bundled post-install script. Run it once if we detect that setup.
python3_real="$(python3 -c 'import sys; print(sys.executable)' 2>/dev/null || true)"
if [[ "$python3_real" == /Library/Frameworks/Python.framework/* ]]; then
    if ! python3 -c 'import ssl, urllib.request; urllib.request.urlopen("https://example.com", timeout=5)' >/dev/null 2>&1; then
        cert_cmd="$(ls -1d /Applications/Python\ 3.*/Install\ Certificates.command 2>/dev/null | tail -n1 || true)"
        if [[ -n "$cert_cmd" && -x "$cert_cmd" ]]; then
            warn "Python.org Python detected without CA certs — running Install Certificates.command"
            if "$cert_cmd" >/dev/null 2>&1; then
                ok "CA certificates installed"
            else
                warn "CA install failed — run it manually: $cert_cmd"
            fi
        else
            warn "Python.org Python appears to lack CA certs; install manually with Install\\ Certificates.command"
        fi
    fi
fi

if command -v claude >/dev/null 2>&1; then
    ok "claude CLI: $(command -v claude) (used for summary generation via your Claude Code subscription)"
else
    warn "claude CLI not on PATH — the hook will fall back to a heuristic summary."
    info "  Install Claude Code from https://claude.ai/code and make sure 'claude' is on PATH."
fi

if [[ ! -f "$HOOK_SRC" ]]; then
    fail "Expected hook source at $HOOK_SRC but it's missing. Run this script from the folder containing vibe_diary_hook.py."
fi
ok "Found vibe_diary_hook.py"

# jq is optional but makes settings.json merging robust; fall back to Python if missing.
if command -v jq >/dev/null 2>&1; then
    merge_tool="jq"
    ok "jq: $(command -v jq)"
else
    merge_tool="python"
    warn "jq not found; using python3 for settings.json merging (works fine, just FYI)"
fi

# ----- step 1: copy the hook -----
step "Installing hook script to $HOOK_DST"
mkdir -p "$HOOKS_DIR"
cp "$HOOK_SRC" "$HOOK_DST"
chmod +x "$HOOK_DST"
ok "Copied and chmod +x"

# ----- step 2: env file -----
step "Creating $ENV_FILE"
if [[ -f "$ENV_FILE" ]]; then
    ok "Already exists — leaving it untouched"
else
    cat > "$ENV_FILE" <<'EOF'
# Credentials for the Claude Code vibe-coding diary hook.
# Fill these in, then chmod stays at 600 (set by installer).

# Your Confluence site, e.g. https://yourcompany.atlassian.net/wiki
CONFLUENCE_BASE_URL=

# Email associated with your Atlassian account
CONFLUENCE_EMAIL=

# Generate at: https://id.atlassian.com/manage-profile/security/api-tokens
CONFLUENCE_API_TOKEN=

# Numeric ID of your diary page. Open the page in Confluence — the URL looks
# like .../pages/123456789/Page+Title — copy the number.
CONFLUENCE_PAGE_ID=

# Note: the summary is generated by shelling out to `claude -p`, which uses
# whatever auth your Claude Code CLI already has (subscription or API key).
# No separate ANTHROPIC_API_KEY is needed here.
EOF
    chmod 600 "$ENV_FILE"
    ok "Wrote template with placeholders (chmod 600)"
fi

# ----- step 3: register the hook in settings.json -----
step "Registering SessionEnd hook in $SETTINGS_FILE"

# Ensure the file exists and contains valid JSON
if [[ ! -f "$SETTINGS_FILE" ]]; then
    echo '{}' > "$SETTINGS_FILE"
    ok "Created fresh settings.json"
else
    # Back it up first — we're about to edit it. Timestamp the filename so
    # re-running the installer doesn't clobber a previous backup.
    backup="${SETTINGS_FILE}.vibe-diary.$(date +%Y%m%d-%H%M%S).bak"
    cp "$SETTINGS_FILE" "$backup"
    ok "Backed up existing settings.json to $(basename "$backup")"
fi

HOOK_CMD="python3 ${HOOK_DST}"

if [[ "$merge_tool" == "jq" ]]; then
    # Build the updated settings with jq, preserving anything else the user has.
    # Idempotency: only append our entry if no SessionEnd hook already runs our script.
    tmp="$(mktemp)"
    jq --arg cmd "$HOOK_CMD" '
        .hooks //= {} |
        .hooks.SessionEnd //= [] |
        if any(.hooks.SessionEnd[]?; (.hooks // [])[]?.command == $cmd)
        then .
        else .hooks.SessionEnd += [{
            "hooks": [{"type": "command", "command": $cmd}]
        }]
        end
    ' "$SETTINGS_FILE" > "$tmp"
    mv "$tmp" "$SETTINGS_FILE"
else
    # Python fallback — same logic, using stdlib json.
    python3 - "$SETTINGS_FILE" "$HOOK_CMD" <<'PYEOF'
import json, sys
settings_path, hook_cmd = sys.argv[1], sys.argv[2]
with open(settings_path) as fh:
    data = json.load(fh)
hooks = data.setdefault("hooks", {})
sess_end = hooks.setdefault("SessionEnd", [])

# Already installed?
already = False
for group in sess_end:
    for h in group.get("hooks", []):
        if h.get("command") == hook_cmd:
            already = True
            break
    if already:
        break

if not already:
    sess_end.append({"hooks": [{"type": "command", "command": hook_cmd}]})

with open(settings_path, "w") as fh:
    json.dump(data, fh, indent=2)
    fh.write("\n")
PYEOF
fi
ok "SessionEnd hook registered"

# ----- step 4: smoke test -----
step "Running smoke test"
if [[ -f "$TEST_FILE" ]]; then
    if python3 "$TEST_FILE" >/dev/null 2>&1; then
        ok "test_hook.py passed"
    else
        warn "test_hook.py failed — not a blocker for install, but investigate:"
        info "  python3 $TEST_FILE"
    fi
else
    warn "test_hook.py not found alongside the installer — skipping"
fi

# ----- done -----
printf "\n%s%sInstall complete.%s\n\n" "$c_bold" "$c_green" "$c_reset"
echo "Next steps:"
echo "  1. Edit $ENV_FILE and fill in the 4 Confluence credentials."
echo "  2. Restart Claude Code (or run '/hooks' inside it to re-check hook config)."
echo "  3. Open a session in a git repo, do something, exit — then check:"
echo "       - Your Confluence page for a new row"
echo "       - ~/.claude/vibe-diary.log if nothing shows up"
echo
echo "To uninstall: remove the SessionEnd entry from $SETTINGS_FILE,"
echo "delete $HOOK_DST and $ENV_FILE."
