def git_info(cwd: Path) -> dict[str, str]:
    """Return branch + github URL for the given directory (best-effort)."""
    info = {"branch": "", "github_url": ""}
    try:
        branch = subprocess.check_output(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=cwd, text=True, stderr=subprocess.DEVNULL,
        ).strip()
        info["branch"] = branch
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass

    try:
        remote = subprocess.check_output(
            ["git", "config", "--get", "remote.origin.url"],
            cwd=cwd, text=True, stderr=subprocess.DEVNULL,
        ).strip()
        info["github_url"] = _normalize_git_url(remote)
    except (subprocess.CalledProcessError, FileNotFoundError):
        pass

    return info


def _normalize_git_url(url: str) -> str:
    """Convert SSH/HTTPS git remotes to an https:// URL, if possible."""
    if not url:
        return ""
    # git@github.com:owner/repo.git -> https://github.com/owner/repo
    m = re.match(r"git@([^:]+):(.+?)(?:\.git)?$", url)
    if m:
        return f"https://{m.group(1)}/{m.group(2)}"
    # https://github.com/owner/repo.git -> strip .git
    if url.startswith(("http://", "https://")):
        return url[:-4] if url.endswith(".git") else url
    return url


