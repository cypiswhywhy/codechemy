@dataclass
class SessionStats:
    session_id: str
    started_at: str            # ISO 8601
    ended_at: str              # ISO 8601
    models: list[str] = field(default_factory=list)
    input_tokens: int = 0
    output_tokens: int = 0
    cache_creation_tokens: int = 0
    cache_read_tokens: int = 0
    cost_usd: float = 0.0
    message_count: int = 0
    user_messages: list[str] = field(default_factory=list)
    assistant_texts: list[str] = field(default_factory=list)
    tools_used: list[str] = field(default_factory=list)
    files_touched: list[str] = field(default_factory=list)

    @property
    def total_tokens(self) -> int:
        return (self.input_tokens + self.output_tokens
                + self.cache_creation_tokens + self.cache_read_tokens)

    @property
    def primary_model(self) -> str:
        return self.models[0] if self.models else "unknown"


# ---------------------------------------------------------------------------
# Transcript parsing
# ---------------------------------------------------------------------------

def parse_transcript(transcript_path: Path, session_id: str) -> SessionStats:
    """Walk the JSONL transcript and aggregate stats for this session."""
    stats = SessionStats(
        session_id=session_id,
        started_at="",
        ended_at="",
    )
    seen_models: set[str] = set()
    seen_tools: set[str] = set()
    seen_files: set[str] = set()

    with transcript_path.open("r", encoding="utf-8") as fh:
        for line_num, line in enumerate(fh, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError as exc:
                log.warning("Bad JSONL at line %d: %s", line_num, exc)
                continue

            ts = entry.get("timestamp")
            if ts:
                if not stats.started_at:
                    stats.started_at = ts
                stats.ended_at = ts

            etype = entry.get("type")

            if etype == "user":
                stats.message_count += 1
                content = _flatten_content(entry.get("message", {}).get("content"))
                if content:
                    stats.user_messages.append(content[:500])

            elif etype == "assistant":
                stats.message_count += 1
                msg = entry.get("message", {}) or {}
                model = msg.get("model")
                if model and model not in seen_models:
                    seen_models.add(model)
                    stats.models.append(model)

                usage = msg.get("usage") or {}
                stats.input_tokens         += int(usage.get("input_tokens", 0) or 0)
                stats.output_tokens        += int(usage.get("output_tokens", 0) or 0)
                stats.cache_creation_tokens+= int(usage.get("cache_creation_input_tokens", 0) or 0)
                stats.cache_read_tokens    += int(usage.get("cache_read_input_tokens", 0) or 0)

                for block in msg.get("content", []) or []:
                    btype = block.get("type")
                    if btype == "text":
                        txt = block.get("text", "").strip()
                        if txt:
                            stats.assistant_texts.append(txt[:1000])
                    elif btype == "tool_use":
                        tool = block.get("name", "")
                        if tool and tool not in seen_tools:
                            seen_tools.add(tool)
                            stats.tools_used.append(tool)
                        # Capture file paths from common file-editing tools
                        ti = block.get("input", {}) or {}
                        for key in ("file_path", "path", "notebook_path"):
                            fp = ti.get(key)
                            if fp and fp not in seen_files:
                                seen_files.add(fp)
                                stats.files_touched.append(fp)

    stats.cost_usd = _calculate_cost(stats)
    return stats


def _flatten_content(content: Any) -> str:
    """User message content can be a string or a list of blocks. Flatten it."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                parts.append(block.get("text", ""))
            elif isinstance(block, str):
                parts.append(block)
        return "\n".join(p for p in parts if p)
    return ""


def _calculate_cost(stats: SessionStats) -> float:
    """Best-effort USD cost from per-model rates."""
    if not stats.models:
        return 0.0
    # Use the first model we saw as the primary for pricing. If multiple
    # models appear, we approximate - good enough for a diary.
    prices = _match_prices(stats.primary_model)
    if not prices:
        return 0.0
    cost = (
        stats.input_tokens          * prices["input"]       / 1_000_000 +
        stats.output_tokens         * prices["output"]      / 1_000_000 +
        stats.cache_creation_tokens * prices["cache_write"] / 1_000_000 +
        stats.cache_read_tokens     * prices["cache_read"]  / 1_000_000
    )
    return round(cost, 4)


def _match_prices(model: str) -> dict | None:
    for prefix, prices in MODEL_PRICES.items():
        if model.startswith(prefix):
            return prices
    log.warning("No price known for model %r - cost will be 0", model)
    return None


