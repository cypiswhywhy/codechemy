# The diary page contains a single table with a marker comment so we can find
# it even if the user adds prose around it. Each task is a row whose first
# cell starts with `data-task="<branch>"` so we can find and update it.

TABLE_MARKER = "<!-- vibe-diary-table -->"

EMPTY_TABLE_TEMPLATE = (
    TABLE_MARKER + "\n"
    "<table>"
    "<colgroup>"
      "<col /><col /><col /><col /><col /><col /><col />"
    "</colgroup>"
    "<tbody>"
    "<tr>"
      "<th>Task (branch)</th>"
      "<th>Repo</th>"
      "<th>Session start</th>"
      "<th>Session end</th>"
      "<th>Model</th>"
      "<th>Summary</th>"
      "<th>Tokens / cost</th>"
    "</tr>"
    "</tbody>"
    "</table>"
)


def ensure_table(body: str) -> str:
    """Make sure the page body contains our diary table. Add it if missing."""
    if TABLE_MARKER in body:
        return body
    separator = "\n\n" if body.strip() else ""
    return body + separator + EMPTY_TABLE_TEMPLATE


def insert_session_row(
    body: str,
    branch: str,
    github_url: str,
    stats: SessionStats,
    summary: str,
) -> str | None:
    """Insert a new session row into the diary table.

    Rows are grouped by task: the first row for a task has merged cells in
    the Task/Repo columns (rowspan), and subsequent sessions for the same task
    append rows *beneath* it without repeating those cells. We re-render the
    rowspan every time for simplicity.

    Returns the updated body string, or ``None`` if this session_id was
    already recorded on the page (SessionEnd can fire more than once per
    session — on /clear, logout, exit — and we don't want duplicate rows).
    """
    body = ensure_table(body)

    # Split body into {before table}, {table rows}, {after table}
    marker_idx = body.index(TABLE_MARKER)
    before = body[:marker_idx]
    after_marker = body[marker_idx + len(TABLE_MARKER):]

    # Find <tbody>...</tbody>
    tbody_open = after_marker.find("<tbody>")
    tbody_close = after_marker.find("</tbody>")
    if tbody_open == -1 or tbody_close == -1:
        # Malformed table - rebuild it
        log.warning("Malformed diary table found; resetting.")
        after_marker = EMPTY_TABLE_TEMPLATE[len(TABLE_MARKER):]
        tbody_open = after_marker.find("<tbody>")
        tbody_close = after_marker.find("</tbody>")

    tbody_inner = after_marker[tbody_open + len("<tbody>"):tbody_close]
    after_tbody = after_marker[tbody_close:]

    # Parse existing rows into groups keyed by branch.
    groups = _parse_tbody(tbody_inner)

    # Dedupe: if this session_id is already present anywhere on the page,
    # bail out. Keeps SessionEnd replays (clear/logout/exit in one session)
    # from producing duplicate rows.
    if stats.session_id and stats.session_id != "unknown":
        for grp in groups.values():
            for sess in grp["sessions"]:
                if sess.get("session_id") == stats.session_id:
                    return None

    # Append this session to the appropriate group, creating it if new.
    key = branch or "(detached)"
    new_session = {
        "start": _format_ts(stats.started_at),
        "end":   _format_ts(stats.ended_at),
        "model": _short_model(stats.primary_model),
        "summary": summary,
        "tokens_cost": _format_tokens_cost(stats),
        "session_id": stats.session_id,
    }
    group = groups.setdefault(key, {"branch": key, "github_url": github_url, "sessions": []})
    if github_url and not group["github_url"]:
        group["github_url"] = github_url
    group["sessions"].append(new_session)

    # Rebuild tbody: header row (kept as-is) + grouped rows
    new_tbody_inner = _render_tbody(groups)

    new_body = (
        before
        + TABLE_MARKER
        + after_marker[:tbody_open + len("<tbody>")]
        + new_tbody_inner
        + after_tbody
    )
    return new_body


# -- helpers for rendering / parsing --

_ROW_TAG = "data-task"


def _parse_tbody(tbody_inner: str) -> dict[str, dict]:
    """Parse existing data rows back into a groups dict.

    Since we always re-render, we only need to recover enough info to replay
    existing rows. Each task-header row carries `data-task="<branch>"` and
    `data-github="<url>"`. Every session row also carries `data-session="<id>"`
    on its start cell so we can dedupe replays of the same session.
    """
    groups: dict[str, dict] = {}
    for match in re.finditer(r"<tr\b[^>]*>(.*?)</tr>", tbody_inner, flags=re.DOTALL):
        row = match.group(1)
        if "<th" in row:
            continue  # skip the column header row, we re-add it
        task_m = re.search(r"data-task=\"([^\"]+)\"", row)
        if not task_m:
            continue
        branch = task_m.group(1)
        grp = groups.setdefault(
            branch,
            {"branch": branch, "github_url": "", "sessions": []},
        )
        gh_m = re.search(r"data-github=\"([^\"]*)\"", row)
        if gh_m and gh_m.group(1):
            grp["github_url"] = gh_m.group(1)

        sess_m = re.search(r'data-session="([^"]*)"', row)
        session_id = sess_m.group(1) if sess_m else ""

        # Extract session cells. Our rows always have the last 5 cells as
        # start / end / model / summary / tokens_cost.
        cells = re.findall(r"<td\b[^>]*>(.*?)</td>", row, flags=re.DOTALL)
        if len(cells) >= 5:
            session = {
                "start":       _strip_html(cells[-5]),
                "end":         _strip_html(cells[-4]),
                "model":       _strip_html(cells[-3]),
                "summary":     _unescape_text(cells[-2]),
                "tokens_cost": _strip_html(cells[-1]),
                "session_id":  session_id,
            }
            grp["sessions"].append(session)
    return groups


def _render_tbody(groups: dict[str, dict]) -> str:
    # Header row
    out = [(
        "<tr>"
        "<th>Task (branch)</th>"
        "<th>Repo</th>"
        "<th>Session start</th>"
        "<th>Session end</th>"
        "<th>Model</th>"
        "<th>Summary</th>"
        "<th>Tokens / cost</th>"
        "</tr>"
    )]

    # Sort groups: most recently active first
    def last_start(g):
        return g["sessions"][-1]["start"] if g["sessions"] else ""
    sorted_groups = sorted(groups.values(), key=last_start, reverse=True)

    for grp in sorted_groups:
        sessions = grp["sessions"]
        rowspan = len(sessions) or 1
        branch = grp["branch"]
        gh = grp["github_url"]
        branch_attr = escape(branch, quote=True)
        for i, s in enumerate(sessions):
            if i == 0:
                task_cell = (
                    f'<td rowspan="{rowspan}" data-task="{branch_attr}" '
                    f'data-github="{escape(gh, quote=True)}">'
                    f'<p><strong>{escape(branch)}</strong></p>'
                    f'</td>'
                )
                repo_cell = (
                    f'<td rowspan="{rowspan}">'
                    + (_link(gh, _repo_label(gh)) if gh else "<p>-</p>")
                    + '</td>'
                )
                prefix = task_cell + repo_cell
            else:
                # Continuation row: the Task/Repo columns are covered by the
                # first row's rowspan, so we emit no prefix here. The start
                # cell below carries data-task so the parser can still find
                # the group on round-trip.
                prefix = ""

            sess_attr = escape(s.get("session_id", "") or "", quote=True)
            start_cell = (
                f'<td data-task="{branch_attr}" data-session="{sess_attr}">'
                f'{escape(s["start"])}</td>'
            )
            row_cells = (
                start_cell
                + f'<td>{escape(s["end"])}</td>'
                + f'<td>{escape(s["model"])}</td>'
                + f'<td>{_paragraph(s["summary"])}</td>'
                + f'<td>{escape(s["tokens_cost"])}</td>'
            )
            out.append("<tr>" + prefix + row_cells + "</tr>")
    return "".join(out)


def _link(href: str, text: str) -> str:
    safe_href = escape(href, quote=True)
    return f'<p><a href="{safe_href}">{escape(text)}</a></p>'


def _paragraph(text: str) -> str:
    return f"<p>{escape(text)}</p>"


def _repo_label(url: str) -> str:
    # github.com/owner/repo -> owner/repo
    m = re.search(r"github\.com/([^/]+/[^/?#]+)", url)
    return m.group(1) if m else url


def _strip_html(s: str) -> str:
    return re.sub(r"<[^>]+>", "", s).strip()


def _unescape_text(s: str) -> str:
    from html import unescape
    return unescape(_strip_html(s))


def _format_ts(iso: str) -> str:
    if not iso:
        return "?"
    try:
        dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return dt.astimezone().strftime("%Y-%m-%d %H:%M")
    except ValueError:
        return iso


def _short_model(model: str) -> str:
    if not model or model == "unknown":
        return "?"
    # claude-sonnet-4-5-20250929 -> sonnet-4-5
    m = re.match(r"claude-([a-z0-9-]+?)-\d{8}$", model)
    if m:
        return m.group(1)
    return model.replace("claude-", "")


def _format_tokens_cost(stats: SessionStats) -> str:
    total = stats.total_tokens
    if stats.cost_usd:
        return f"{_fmt_num(total)} tok / ${stats.cost_usd:.3f}"
    return f"{_fmt_num(total)} tok"


def _fmt_num(n: int) -> str:
    if n >= 1_000_000:
        return f"{n/1_000_000:.2f}M"
    if n >= 1_000:
        return f"{n/1_000:.1f}k"
    return str(n)


