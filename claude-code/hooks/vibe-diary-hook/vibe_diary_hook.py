class ConfluenceError(RuntimeError):
    """Confluence API error carrying the HTTP status code."""
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status


def _build_ssl_context() -> ssl.SSLContext:
    """Build an SSL context that works even when Python.org's Python on macOS
    was installed without running ``Install Certificates.command``.

    Strategy: start with the default context, then stack on any common
    system/Homebrew CA bundles we find. As a last resort use ``certifi`` if
    it happens to be installed. If *all* of this fails, the default is still
    in effect and the caller gets the original SSLCertVerificationError.
    """
    ctx = ssl.create_default_context()
    for candidate in (
        "/etc/ssl/cert.pem",                           # macOS system
        "/etc/pki/tls/certs/ca-bundle.crt",            # RHEL/Fedora
        "/etc/ssl/certs/ca-certificates.crt",          # Debian/Ubuntu
        "/opt/homebrew/etc/ca-certificates/cert.pem",  # Apple Silicon Homebrew
        "/usr/local/etc/ca-certificates/cert.pem",     # Intel Homebrew
        "/opt/homebrew/etc/openssl@3/cert.pem",
        "/usr/local/etc/openssl@3/cert.pem",
    ):
        if os.path.isfile(candidate):
            try:
                ctx.load_verify_locations(cafile=candidate)
            except ssl.SSLError:
                continue
    try:
        import certifi  # type: ignore[import-not-found]
        ctx.load_verify_locations(cafile=certifi.where())
    except Exception:
        pass
    return ctx


_SSL_CTX: ssl.SSLContext | None = None


def _ssl_ctx() -> ssl.SSLContext:
    global _SSL_CTX
    if _SSL_CTX is None:
        _SSL_CTX = _build_ssl_context()
    return _SSL_CTX


class Confluence:
    def __init__(self, base_url: str, email: str, token: str):
        self.base_url = base_url.rstrip("/")
        # Atlassian Cloud uses HTTP Basic with email:token
        import base64
        creds = base64.b64encode(f"{email}:{token}".encode()).decode()
        self.headers = {
            "authorization": f"Basic {creds}",
            "accept": "application/json",
            "content-type": "application/json",
        }

    def _request(self, method: str, path: str, body: dict | None = None) -> dict:
        url = f"{self.base_url}{path}"
        data = json.dumps(body).encode("utf-8") if body is not None else None
        req = urlrequest.Request(url, data=data, headers=self.headers, method=method)
        try:
            with urlrequest.urlopen(req, timeout=30, context=_ssl_ctx()) as resp:
                raw = resp.read().decode("utf-8")
                return json.loads(raw) if raw else {}
        except HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")[:500]
            raise ConfluenceError(
                exc.code,
                f"Confluence {method} {path} -> {exc.code}: {detail}",
            ) from exc
        except ssl.SSLCertVerificationError as exc:
            raise ConfluenceError(
                0,
                f"Confluence {method} {path} -> SSL cert verify failed: {exc}. "
                "On macOS with Python.org's Python, run "
                "'/Applications/Python\\ 3.12/Install\\ Certificates.command' "
                "once, or install 'certifi' (pip install certifi).",
            ) from exc

    def get_page(self, page_id: str) -> dict:
        return self._request(
            "GET",
            f"/rest/api/content/{page_id}?expand=body.storage,version,space,title",
        )

    def update_page(self, page_id: str, title: str, body_storage: str, new_version: int, space_key: str) -> dict:
        payload = {
            "id": page_id,
            "type": "page",
            "title": title,
            "space": {"key": space_key},
            "body": {"storage": {"value": body_storage, "representation": "storage"}},
            "version": {"number": new_version},
        }
        return self._request("PUT", f"/rest/api/content/{page_id}", payload)


