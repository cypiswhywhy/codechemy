def generate_summary(stats: SessionStats) -> str:
    """Ask Claude for a 1-2 sentence summary by shelling out to the `claude` CLI.

    Using the CLI means the summary runs under whatever auth Claude Code
    already has set up (subscription or API key) — no separate API token
    needed. We set VIBE_DIARY_SKIP=1 in the subprocess so the sub-session's
    own SessionEnd doesn't recurse into this hook.
    """
    if stats.message_count == 0:
        return "(empty session)"

    # Build a compact prompt: first user message + tools + files + last assistant text
    first_prompt = stats.user_messages[0] if stats.user_messages else ""
    last_reply   = stats.assistant_texts[-1] if stats.assistant_texts else ""

    context_lines = [
        f"First user request: {first_prompt[:600]}",
        f"Tools used: {', '.join(stats.tools_used[:15]) or 'none'}",
        f"Files touched: {', '.join(stats.files_touched[:10]) or 'none'}",
        f"Final assistant message: {last_reply[:600]}",
    ]
    user_prompt = (
        "Summarize what was accomplished in this Claude Code session in "
        "1-2 concise sentences for a work diary. Focus on *what changed*, "
        "not on what was discussed. No preamble, no quotes.\n\n"
        + "\n".join(context_lines)
    )

    claude_bin = shutil.which("claude")
    if not claude_bin:
        log.error("`claude` CLI not found on PATH - using fallback summary")
        return _fallback_summary(stats)

    env = os.environ.copy()
    env["VIBE_DIARY_SKIP"] = "1"  # prevent recursion if the sub-session triggers SessionEnd

    try:
        result = subprocess.run(
            [claude_bin, "-p", user_prompt,
             "--model", SUMMARY_MODEL,
             "--output-format", "text"],
            capture_output=True, text=True, timeout=60, env=env,
        )
    except subprocess.TimeoutExpired:
        log.error("`claude -p` timed out after 60s")
        return _fallback_summary(stats)
    except OSError as exc:
        log.error("`claude -p` failed to start: %s", exc)
        return _fallback_summary(stats)

    if result.returncode != 0:
        log.error("`claude -p` exited %d: %s",
                  result.returncode, (result.stderr or "")[:500])
        return _fallback_summary(stats)

    summary = (result.stdout or "").strip()
    return summary or _fallback_summary(stats)


def _fallback_summary(stats: SessionStats) -> str:
    """Used when the summary API call fails."""
    parts = []
    if stats.files_touched:
        parts.append(f"Worked on {len(stats.files_touched)} file(s)")
    if stats.tools_used:
        parts.append(f"using {', '.join(stats.tools_used[:4])}")
    return " ".join(parts) or "(no summary available)"


