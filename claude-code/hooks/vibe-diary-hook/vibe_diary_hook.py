def main() -> int:
    # Recursion guard: our own `claude -p` subprocess will trigger SessionEnd
    # when it exits, re-entering this hook. Bail fast when we see the marker.
    if os.environ.get("VIBE_DIARY_SKIP") == "1":
        return 0

    try:
        hook_input = json.load(sys.stdin)
    except json.JSONDecodeError as exc:
        log.error("Invalid JSON on stdin: %s", exc)
        return 0  # non-blocking: don't break the user's session teardown

    session_id      = hook_input.get("session_id", "unknown")
    transcript_path = Path(hook_input.get("transcript_path", ""))
    cwd             = Path(hook_input.get("cwd") or os.getcwd())
    reason          = hook_input.get("reason", "?")

    log.info("SessionEnd: session=%s reason=%s cwd=%s", session_id, reason, cwd)

    _load_env_file(Path.home() / ".claude" / "vibe-diary.env")

    missing = [v for v in (
        "CONFLUENCE_BASE_URL", "CONFLUENCE_EMAIL", "CONFLUENCE_API_TOKEN",
        "CONFLUENCE_PAGE_ID",
    ) if not os.environ.get(v)]
    if missing:
        log.error("Missing env vars: %s - skipping diary update", ", ".join(missing))
        return 0

    if not transcript_path.is_file():
        log.error("Transcript not found: %s", transcript_path)
        return 0

    try:
        stats = parse_transcript(transcript_path, session_id)
    except Exception as exc:
        log.error("Transcript parse failed: %s\n%s", exc, traceback.format_exc())
        return 0

    min_msgs = int(os.environ.get("VIBE_DIARY_MIN_MESSAGES", "2"))
    if stats.message_count < min_msgs:
        log.info("Session too short (%d msgs) - skipping", stats.message_count)
        return 0

    gi = git_info(cwd)
    branch = gi["branch"] or f"(no-branch:{cwd.name})"
    github_url = gi["github_url"]
    log.info("Task branch=%s repo=%s", branch, github_url or "-")

    # The rest — summary generation (spawns `claude -p`) and two Confluence
    # round-trips — can take several seconds. Detach from Claude Code so it
    # can finish shutting down without waiting on us. Errors beyond this
    # point are invisible to the user; they go to the log file only.
    _daemonize()

    summary = generate_summary(stats)
    log.info("Summary: %s", summary)

    _update_confluence_with_retry(branch, github_url, stats, summary)
    return 0


def _update_confluence_with_retry(
    branch: str,
    github_url: str,
    stats: SessionStats,
    summary: str,
) -> None:
    """Fetch page, insert row, PUT it back. Retries on HTTP 409 version
    conflict by re-fetching the current body and re-inserting (our insert
    dedupes by session_id, so replays are safe).
    """
    try:
        conf = Confluence(
            os.environ["CONFLUENCE_BASE_URL"],
            os.environ["CONFLUENCE_EMAIL"],
            os.environ["CONFLUENCE_API_TOKEN"],
        )
    except Exception as exc:
        log.error("Confluence client init failed: %s", exc)
        return

    page_id = os.environ["CONFLUENCE_PAGE_ID"]

    for attempt in range(1, MAX_VERSION_CONFLICT_RETRIES + 1):
        try:
            page = conf.get_page(page_id)
            current_body = page["body"]["storage"]["value"]
            new_body = insert_session_row(current_body, branch, github_url, stats, summary)
            if new_body is None:
                log.info("Session %s already on page — skipping PUT",
                         stats.session_id)
                return
            conf.update_page(
                page_id=page_id,
                title=page["title"],
                body_storage=new_body,
                new_version=page["version"]["number"] + 1,
                space_key=page["space"]["key"],
            )
            log.info("Confluence page updated (attempt %d/%d)",
                     attempt, MAX_VERSION_CONFLICT_RETRIES)
            return
        except ConfluenceError as exc:
            if exc.status == 409 and attempt < MAX_VERSION_CONFLICT_RETRIES:
                delay = random.uniform(0.4, 1.2) * attempt  # linear backoff + jitter
                log.warning("Version conflict (attempt %d/%d); retrying in %.1fs",
                            attempt, MAX_VERSION_CONFLICT_RETRIES, delay)
                time.sleep(delay)
                continue
            log.error("Confluence update failed: %s", exc)
            return
        except Exception as exc:
            log.error("Confluence update failed: %s\n%s", exc, traceback.format_exc())
            return


def _daemonize() -> None:
    """Double-fork so the hook returns to Claude Code immediately.

    POSIX-only. The original process exits with 0 after the first fork;
    the detached grandchild continues running. Stdin/out/err are redirected
    to /dev/null so no output leaks into Claude Code's terminal. Our
    ``logging`` FileHandler keeps its own file descriptor, so log writes
    in the grandchild still land in the log file.
    """
    try:
        if os.fork() > 0:
            os._exit(0)  # original parent exits → Claude Code unblocks
    except OSError as exc:
        log.warning("First fork failed (%s); running inline", exc)
        return
    try:
        os.setsid()
        if os.fork() > 0:
            os._exit(0)  # intermediate exits; grandchild becomes session-less
    except OSError as exc:
        log.warning("Second fork failed (%s); running inline", exc)
        return
    devnull = os.open(os.devnull, os.O_RDWR)
    for fd in (0, 1, 2):
        try:
            os.dup2(devnull, fd)
        except OSError:
            pass


def _load_env_file(path: Path) -> None:
    if not path.is_file():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        os.environ.setdefault(key, value)


if __name__ == "__main__":
    sys.exit(main())
