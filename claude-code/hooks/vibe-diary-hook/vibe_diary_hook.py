#!/usr/bin/env python3
"""
Vibe-coding diary hook for Claude Code.

Runs on SessionEnd. Parses the session transcript, asks Claude for a short
summary, and upserts a row into a Confluence page tracking tasks and sessions.

Task identity = current git branch of the session's cwd.

Required environment variables (put them in ~/.claude/vibe-diary.env or
export them in your shell):
    CONFLUENCE_BASE_URL     e.g. https://yourco.atlassian.net/wiki
    CONFLUENCE_EMAIL        your Atlassian email
    CONFLUENCE_API_TOKEN    https://id.atlassian.com/manage-profile/security/api-tokens
    CONFLUENCE_PAGE_ID      numeric ID of the diary page

The summary is generated by invoking the `claude` CLI in print mode, which
uses whatever auth you've set up for Claude Code (subscription or API key).
No separate ANTHROPIC_API_KEY is needed.

Optional:
    VIBE_DIARY_LOG          path to a log file (default: ~/.claude/vibe-diary.log)
    VIBE_DIARY_MIN_MESSAGES skip sessions with fewer messages than this (default: 2)
    VIBE_DIARY_SKIP         set to 1 to make the hook exit immediately (used
                            internally to prevent recursion when the hook's
                            own `claude -p` subprocess triggers SessionEnd).
"""

